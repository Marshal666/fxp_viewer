def chunk(tag,data):
    return struct.pack(">I",len(data))+tag+data+struct.pack(">I",zlib.crc32(tag+data)&0xffffffff)
size=256
raw=bytearray()
for y in range(size):
    raw.append(0)
    for x in range(size):
        c=210 if ((x//16+y//16)%2) else 160
        raw.extend((c,c,c,255))
png=b"\x89PNG\r\n\x1a\n"+chunk(b"IHDR",struct.pack(">IIBBBBB",size,size,8,6,0,0,0))+chunk(b"IDAT",zlib.compress(raw))+chunk(b"IEND",b"")
(out/"checker.png").write_bytes(png)
