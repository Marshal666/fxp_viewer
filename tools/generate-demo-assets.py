import base64, json, math, struct, zlib
from pathlib import Path
out = Path(__file__).resolve().parents[1] / "examples" / "assets"
out.mkdir(parents=True, exist_ok=True)

def cube(x0,y0,z0,x1,y1,z1):
    faces = [
        ((0,0,1),[(x0,y0,z1),(x1,y0,z1),(x1,y1,z1),(x0,y1,z1)]),
        ((0,0,-1),[(x1,y0,z0),(x0,y0,z0),(x0,y1,z0),(x1,y1,z0)]),
        ((1,0,0),[(x1,y0,z1),(x1,y0,z0),(x1,y1,z0),(x1,y1,z1)]),
        ((-1,0,0),[(x0,y0,z0),(x0,y0,z1),(x0,y1,z1),(x0,y1,z0)]),
        ((0,1,0),[(x0,y1,z1),(x1,y1,z1),(x1,y1,z0),(x0,y1,z0)]),
        ((0,-1,0),[(x0,y0,z0),(x1,y0,z0),(x1,y0,z1),(x0,y0,z1)])]
    pos=[]; normals=[]; uv=[]; indices=[]
    for n, p in faces:
        start=len(pos); pos.extend(p); normals.extend([n]*4)
        uv.extend([(0,0),(1,0),(1,1),(0,1)])
        indices.extend([start+i for i in (0,1,2,0,2,3)])
    return pos,normals,uv,indices

class Gltf:
    def __init__(self):
        self.binary=bytearray()
        self.doc={"asset":{"version":"2.0","generator":"fxp_viewer original demo"},
                  "scene":0,"scenes":[{"nodes":[0]}],"nodes":[],"meshes":[],
                  "bufferViews":[],"accessors":[],"materials":[{"name":"white",
                  "pbrMetallicRoughness":{"baseColorFactor":[1,1,1,1],"metallicFactor":0,"roughnessFactor":1}}]}
    def accessor(self, values, fmt, kind, component, bounds=False):
        while len(self.binary)%4: self.binary.append(0)
        offset=len(self.binary)
        for v in values:
            if not isinstance(v,(tuple,list)): v=[v]
            self.binary.extend(struct.pack("<"+fmt,*v))
        view=len(self.doc["bufferViews"])
        self.doc["bufferViews"].append({"buffer":0,"byteOffset":offset,"byteLength":len(self.binary)-offset})
        a={"bufferView":view,"componentType":component,"count":len(values),"type":kind}
        if bounds:
            rows=[v if isinstance(v,(tuple,list)) else [v] for v in values]
            a["min"]=[min(v[k] for v in rows) for k in range(len(rows[0]))]
            a["max"]=[max(v[k] for v in rows) for k in range(len(rows[0]))]
        self.doc["accessors"].append(a); return len(self.doc["accessors"])-1
    def mesh(self, p,n,u,i,joints=None):
        attrs={"POSITION":self.accessor(p,"3f","VEC3",5126,True),
               "NORMAL":self.accessor(n,"3f","VEC3",5126),
               "TEXCOORD_0":self.accessor(u,"2f","VEC2",5126)}
        if joints is not None:
            attrs["JOINTS_0"]=self.accessor([(j,0,0,0) for j in joints],"4B","VEC4",5121)
            attrs["WEIGHTS_0"]=self.accessor([(1,0,0,0)]*len(p),"4f","VEC4",5126)
        indices=self.accessor(i,"H","SCALAR",5123)
        self.doc["meshes"].append({"primitives":[{"attributes":attrs,"indices":indices,"material":0,"mode":4}]})
    def save(self,name):
        self.doc["buffers"]=[{"byteLength":len(self.binary)}]
        if name.endswith(".gltf"):
            self.doc["buffers"][0]["uri"]="data:application/octet-stream;base64,"+base64.b64encode(self.binary).decode()
            (out/name).write_text(json.dumps(self.doc,indent=2)+"\n")
        else:
            metadata=json.dumps(self.doc,separators=(",",":")).encode()
            metadata+=b" "*((-len(metadata))%4)
            data=bytes(self.binary)+b"\0"*((-len(self.binary))%4)
            content=struct.pack("<II",len(metadata),0x4E4F534A)+metadata+struct.pack("<II",len(data),0x004E4942)+data
            (out/name).write_bytes(struct.pack("<III",0x46546C67,2,len(content)+12)+content)

